#!/usr/bin/env python3
"""Run the complete experiment pipeline in the required order:

1. environment/model validation
2. LFW threshold calibration, Stage 1 (candidates from pairsDevTrain.txt)
3. LFW threshold selection, Stage 2 (freeze on pairsDevTest.txt) + development metrics
4. final LFW evaluation (pairs.txt, frozen threshold)
5. CPLFW evaluation (frozen threshold, no recalibration)
6. real 1:N duplicate gallery evaluation
7. aggregate report generation (run_manifest.json, metrics_summary.csv,
   confusion_matrices.csv, roc_points.csv)

Stops immediately, with the underlying step's own error message, rather
than fabricating a result when a required dataset, protocol, or model file
is missing or invalid.

Usage:
    python scripts/run_complete_experiment.py \
        --dataset-root /path/to/private-storage/datasets \
        --protocol-root /path/to/private-storage/protocols \
        --model-root /path/to/private-storage/models \
        --cplfw-dataset-root /path/to/private-storage/cplfw_raw \
        --cplfw-image-variant raw \
        --output-root results/aggregate
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

from face_verification.artifacts import (
    read_json_artifact,
    utc_now_iso,
    write_csv_artifact,
    write_json_artifact,
    write_markdown_artifact,
)
from face_verification.privacy import default_forbidden_path_substrings, find_path_leaks
from face_verification.provenance import sha256_of_file, software_environment_report

SCRIPTS_DIR = Path(__file__).resolve().parent

VERIFICATION_EXPERIMENTS = ("lfw_development", "lfw_final", "cplfw")


def _run(args: List[str]) -> None:
    printable = " ".join(str(a) for a in args)
    print(f"\n$ {sys.executable} {printable}")
    completed = subprocess.run([sys.executable, *args])
    if completed.returncode != 0:
        raise SystemExit(f"Stopping: step failed (exit code {completed.returncode}): {printable}")


def _fmt_pct(value: Any) -> str:
    try:
        return f"{float(value) * 100:.2f}%"
    except (TypeError, ValueError):
        return "n/a"


def _fmt_num(value: Any, digits: int = 4) -> str:
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return "n/a"


