def _write_aggregate_reports(
    output_root: Path, cli_args: argparse.Namespace, gallery_manifest_path: Path, cplfw_image_variant: str
) -> None:
    threshold_path = output_root / "calibrated_threshold.json"
    payloads: Dict[str, Dict[str, Any]] = {
        "lfw_development": read_json_artifact(output_root / "lfw_development_metrics.json"),
        "lfw_final": read_json_artifact(output_root / "lfw_final_metrics.json"),
        "cplfw": read_json_artifact(output_root / "cplfw_metrics.json"),
    }
    gallery_payload = read_json_artifact(output_root / "duplicate_gallery_metrics.json")
    threshold_payload = read_json_artifact(threshold_path)

    output_files = {
        "calibrated_threshold.json": threshold_path,
        "lfw_development_metrics.json": output_root / "lfw_development_metrics.json",
        "lfw_final_metrics.json": output_root / "lfw_final_metrics.json",
        "cplfw_metrics.json": output_root / "cplfw_metrics.json",
        "duplicate_gallery_metrics.json": output_root / "duplicate_gallery_metrics.json",
    }

    write_json_artifact(
        output_root / "run_manifest.json",
        {
            "artifact_type": "run_manifest",
            "dataset_storage": "access-controlled private research storage; path omitted from public artifacts",
            "dataset_root_variable": "FACE_DATA_ROOT",
            "protocol_root_variable": "FACE_PROTOCOL_ROOT",
            "model_root_variable": "FACE_MODEL_ROOT",
            "cplfw_image_variant": cplfw_image_variant,
            "output_root": str(output_root),
            "gallery_manifest": str(gallery_manifest_path),
            "frozen_threshold": threshold_payload.get("threshold"),
            "frozen_threshold_candidate": threshold_payload.get("operating_strategy"),
            "output_file_sha256": {name: sha256_of_file(path) for name, path in output_files.items()},
            "software_environment": software_environment_report(),
        },
    )

    summary_field_order = [
        "experiment", "protocol_file", "total_pairs", "scored_pairs", "failure_rate", "threshold",
        "accuracy", "precision", "recall", "f1", "false_match_rate", "false_non_match_rate",
        "roc_auc", "equal_error_rate", "embedding_time_mean_ms", "embedding_time_median_ms",
        "embedding_time_p95_ms", "gallery_size", "duplicate_probe_count", "unknown_probe_count",
        "duplicate_detection_rate", "false_duplicate_review_rate", "rank1_identification_rate",
        "true_duplicate_miss_rate", "gallery_search_time_mean_ms", "gallery_search_time_p95_ms",
    ]
    summary_rows = []
    for name in VERIFICATION_EXPERIMENTS:
        payload = payloads[name]
        summary_rows.append({"experiment": name, **{field: payload.get(field, "") for field in summary_field_order[1:]}})
    summary_rows.append(
        {
            "experiment": "duplicate_gallery",
            **{field: gallery_payload.get(field, "") for field in summary_field_order[1:]},
        }
    )
    write_csv_artifact(output_root / "metrics_summary.csv", summary_rows, fieldnames=summary_field_order)

    confusion_fields = ["experiment", "true_positive", "false_positive", "true_negative", "false_negative"]
    confusion_rows = []
    for name in VERIFICATION_EXPERIMENTS:
        matrix = payloads[name].get("confusion_matrix") or {}
        confusion_rows.append({"experiment": name, **{f: matrix.get(f, "") for f in confusion_fields[1:]}})
    write_csv_artifact(output_root / "confusion_matrices.csv", confusion_rows, fieldnames=confusion_fields)

    roc_fields = ["experiment", "threshold", "false_match_rate", "true_match_rate"]
    roc_rows = []
    for name in VERIFICATION_EXPERIMENTS:
        for point in payloads[name].get("roc_points", []):
            roc_rows.append({"experiment": name, **{f: point[f] for f in roc_fields[1:]}})
    write_csv_artifact(output_root / "roc_points.csv", roc_rows, fieldnames=roc_fields)

    write_markdown_artifact(
        output_root / "FINAL_EVALUATION_REPORT.md", _render_final_report(payloads, gallery_payload)
    )

    leaks = find_path_leaks(output_root, forbidden_substrings=default_forbidden_path_substrings())
    if leaks:
        raise SystemExit(
            "Refusing to finish: public aggregate output(s) contain a personal/absolute path:\n"
            + "\n".join(f"  {leak}" for leak in leaks)
        )

    print(
        f"Wrote run_manifest.json, metrics_summary.csv ({len(summary_rows)} rows), "
        f"confusion_matrices.csv ({len(confusion_rows)} rows), roc_points.csv ({len(roc_rows)} rows), "
        f"and FINAL_EVALUATION_REPORT.md to {output_root}"
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--dataset-root", required=True, type=Path,
        help="Root containing lfw_funneled/ and cplfw/ subdirectories",
    )
    parser.add_argument("--protocol-root", required=True, type=Path)
    parser.add_argument("--model-root", required=True, type=Path)
    parser.add_argument("--output-root", required=True, type=Path)
    parser.add_argument(
        "--cplfw-dataset-root", type=Path, default=None,
        help="CPLFW image root, if it lives outside --dataset-root/cplfw (e.g. a "
             "raw extraction kept separate from the aligned copy). Defaults to "
             "--dataset-root/cplfw.",
    )
    parser.add_argument(
        "--cplfw-image-variant", required=True, choices=("raw", "aligned"),
        help="Which CPLFW image set --cplfw-dataset-root points at. See "
             "scripts/evaluate_cplfw.py.",
    )
    parser.add_argument(
        "--gallery-manifest", type=Path, default=Path("results/raw/gallery_manifest.json"),
        help="Where to write the private gallery manifest (must stay out of Git).",
    )
    args = parser.parse_args(argv)

    lfw_root = args.dataset_root / "lfw_funneled"
    cplfw_root = args.cplfw_dataset_root if args.cplfw_dataset_root is not None else args.dataset_root / "cplfw"
    output_root = args.output_root
    output_root.mkdir(parents=True, exist_ok=True)

    threshold_artifact = output_root / "calibrated_threshold.json"
    dev_metrics = output_root / "lfw_development_metrics.json"
    final_metrics = output_root / "lfw_final_metrics.json"
    cplfw_metrics = output_root / "cplfw_metrics.json"
    duplicate_metrics = output_root / "duplicate_gallery_metrics.json"

    _run([str(SCRIPTS_DIR / "check_environment.py")])
    _run([str(SCRIPTS_DIR / "verify_models.py"), "--model-root", str(args.model_root)])
    _run([
        str(SCRIPTS_DIR / "verify_lfw_dataset.py"),
        "--dataset-root", str(lfw_root), "--protocol-root", str(args.protocol_root),
    ])
    _run([
        str(SCRIPTS_DIR / "verify_cplfw_dataset.py"),
        "--dataset-root", str(cplfw_root), "--protocol-root", str(args.protocol_root),
        "--image-variant", args.cplfw_image_variant,
    ])

    _run([
        str(SCRIPTS_DIR / "calibrate_lfw.py"),
        "--dataset-root", str(lfw_root), "--protocol-root", str(args.protocol_root),
        "--model-root", str(args.model_root), "--output", str(threshold_artifact),
    ])
    _run([
        str(SCRIPTS_DIR / "evaluate_lfw.py"), "--split", "dev",
        "--dataset-root", str(lfw_root), "--protocol-root", str(args.protocol_root),
        "--model-root", str(args.model_root), "--threshold-artifact", str(threshold_artifact),
        "--output", str(dev_metrics),
    ])
    _run([
        str(SCRIPTS_DIR / "evaluate_lfw.py"), "--split", "final",
        "--dataset-root", str(lfw_root), "--protocol-root", str(args.protocol_root),
        "--model-root", str(args.model_root), "--threshold-artifact", str(threshold_artifact),
        "--output", str(final_metrics),
    ])
    _run([
        str(SCRIPTS_DIR / "evaluate_cplfw.py"),
        "--dataset-root", str(cplfw_root), "--protocol-root", str(args.protocol_root),
        "--model-root", str(args.model_root), "--image-variant", args.cplfw_image_variant,
        "--threshold-artifact", str(threshold_artifact),
        "--output", str(cplfw_metrics),
    ])
    _run([
        str(SCRIPTS_DIR / "create_gallery_manifest.py"),
        "--dataset-root", str(lfw_root), "--protocol-root", str(args.protocol_root),
        "--output", str(args.gallery_manifest),
    ])
    _run([
        str(SCRIPTS_DIR / "evaluate_duplicate_gallery.py"),
        "--manifest", str(args.gallery_manifest), "--model-root", str(args.model_root),
        "--threshold-artifact", str(threshold_artifact), "--output", str(duplicate_metrics),
    ])

    _write_aggregate_reports(output_root, args, args.gallery_manifest, args.cplfw_image_variant)

    print(f"\nComplete. Aggregate results are in {output_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
